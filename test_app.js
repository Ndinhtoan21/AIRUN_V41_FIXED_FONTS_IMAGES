'use strict';
const assert=require('node:assert/strict');
const {WARDS,aqiInfo,uvInfo,analyzeSnapshot,fallbackData,haversine,escapeHTML,formatPace,formatDuration,gpsLevel,parsePace,planEstimate}=require('./app.js');
assert.equal(WARDS.length,23);
assert.equal(new Set(WARDS.map(x=>x.key)).size,23);
assert.ok(WARDS.every(x=>Number.isFinite(x.lat)&&Number.isFinite(x.lon)));
const plan={intensity:'Nhẹ',duration:30,sensitive:false};
const good={aqi:35,pm:7,temp:26,feels:27,wind:8,rain:10,uv:1};
const bad={aqi:180,pm:70,temp:35,feels:40,wind:40,rain:85,uv:9};
assert.ok(analyzeSnapshot(good,plan).score>=7.5);
assert.ok(analyzeSnapshot(bad,plan).score<5);
assert.ok(analyzeSnapshot({...good,aqi:90},{...plan,sensitive:true}).score<analyzeSnapshot({...good,aqi:90},plan).score);
assert.equal(aqiInfo(50).label,'Tốt');
assert.equal(aqiInfo(151).tone,'bad');
assert.equal(uvInfo(8).tone,'bad');
const fallback=fallbackData(WARDS[0]);
assert.equal(fallback.source,'demo');
assert.equal(fallback.hourly.length,48);
assert.ok(fallback.hourly.every(x=>Number.isFinite(x.aqi)&&Number.isFinite(x.temp)&&Number.isFinite(x.uv)));
assert.ok(haversine(16.06,108.22,16.06,108.22)<.001);
assert.equal(escapeHTML('<script>'),'&lt;script&gt;');
assert.equal(formatPace(7),'7:00');
assert.equal(formatDuration(3661),'01:01:01');
assert.equal(gpsLevel(9),4);assert.equal(gpsLevel(90),0);
assert.equal(parsePace('6:30'),6.5);
assert.equal(parsePace('6.5'),6.5);
assert.equal(parsePace('6:75'),null);
const est=planEstimate({duration:60,pace:6,intensity:'Vừa'});assert.equal(est.distance,10);assert.equal(est.speed,10);
console.log('AIRUN V5.4 tests: OK');
